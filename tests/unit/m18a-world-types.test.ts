import { describe, expect, test } from 'vitest';
import { deriveSeed, hashString } from '../../src/engine/rng';
import { createDefaultPipeline } from '../../src/gen/pipeline';
import { sampleTerrainTopY } from '../../src/gen/terrain-height';
import {
  DEFAULT_WORLD_OPTIONS,
  isWorldType,
  normalizeWorldOptions,
  terrainVariant,
  withTerrainVariant,
  type TerrainVariant,
} from '../../src/gen/world-options';
import { deserializeWorldMetadata, serializeWorldMetadata } from '../../src/persist/serializers';
import { World } from '../../src/world/world';
import '../../src/gameplay/chests';

/** worldHash of blocks (-24..39)² generated by the pipeline with `variant`. */
function generatedHash(seed: string, variant?: TerrainVariant): { hash: string; world: World } {
  const world = new World();
  const pipeline = createDefaultPipeline();
  const worldSeed = hashString(seed);
  const hash = world.worldHash(-24, -24, 39, 39, (cx, cz) => {
    pipeline.generateColumn(worldSeed, cx, cz, world.getColumn(cx, cz, true)!, variant);
  });
  return { hash, world };
}

describe('M18a world types', () => {
  test('Default generation is unchanged: worldHash equals the value master produced', () => {
    // Golden values computed on master (fa0bb62) with the same region and pipeline.
    expect(generatedHash('blockcraft-test-seed-42').hash).toBe('e0d9ecf0');
    expect(generatedHash('abc').hash).toBe('22a82135');
    expect(generatedHash('abc', { type: 'default' }).hash).toBe('22a82135');
  });

  test('Amplified reaches above y 250 near the standard seed origin and stays within the world', () => {
    const terrainSeed = deriveSeed(hashString('blockcraft-test-seed-42'), 'terrain_shape');
    let defaultMax = 0;
    let amplifiedMax = 0;
    for (let x = -64; x < 64; x += 2)
      for (let z = -64; z < 64; z += 2) {
        defaultMax = Math.max(defaultMax, sampleTerrainTopY(terrainSeed, x, z));
        withTerrainVariant({ type: 'amplified' }, () => {
          amplifiedMax = Math.max(amplifiedMax, sampleTerrainTopY(terrainSeed, x, z));
        });
      }
    expect(defaultMax).toBeLessThan(200);
    expect(amplifiedMax).toBeGreaterThan(250);
    expect(amplifiedMax).toBeLessThanOrEqual(319);

    // The generated blocks agree with the height probe: the peak column really is that tall.
    const world = new World();
    const pipeline = createDefaultPipeline();
    pipeline.generateColumn(hashString('blockcraft-test-seed-42'), -2, 2, world.getColumn(-2, 2, true)!, {
      type: 'amplified',
    });
    let peak = 0;
    for (let x = -32; x < -16; x++) for (let z = 32; z < 48; z++) peak = Math.max(peak, world.getHeight(x, z));
    expect(peak).toBeGreaterThan(250);
    // The ambient variant is restored after the column.
    expect(terrainVariant().type).toBe('default');
  });

  test('Amplified worlds still carve caves and fill aquifers and oceans', () => {
    const { world } = generatedHash('blockcraft-test-seed-42', { type: 'amplified' });
    let caveAir = 0;
    let water = 0;
    for (let x = -24; x < 40; x += 1)
      for (let z = -24; z < 40; z += 1) {
        const top = world.getHeight(x, z);
        for (let y = 8; y < top - 8; y += 2) {
          const id = world.getBlock(x, y, z).id;
          if (id === 'air' || id === 'cave_air') caveAir++;
          if (id === 'water') water++;
        }
      }
    expect(caveAir).toBeGreaterThan(50);
    expect(water + caveAir).toBeGreaterThan(50);
  });

  test('Amplified and default differ; the same variant and seed repeat exactly', () => {
    const a = generatedHash('abc', { type: 'amplified' }).hash;
    expect(a).not.toBe('22a82135');
    expect(generatedHash('abc', { type: 'amplified' }).hash).toBe(a);
  });

  test('Single Biome uses the chosen biome everywhere while the terrain shape follows the noise', () => {
    const { world } = generatedHash('blockcraft-test-seed-42', {
      type: 'single_biome',
      biome: 'desert',
    });
    const heights = new Set<number>();
    for (let x = -24; x < 40; x += 3)
      for (let z = -24; z < 40; z += 3) {
        expect(world.getBiome(x, z)).toBe('desert');
        heights.add(world.getHeight(x, z));
      }
    expect(heights.size).toBeGreaterThan(5);
    const { world: defaultWorld } = generatedHash('blockcraft-test-seed-42');
    const biomes = new Set<string>();
    for (let x = -24; x < 40; x += 3)
      for (let z = -24; z < 40; z += 3) biomes.add(defaultWorld.getBiome(x, z));
    expect(biomes.has('desert') && biomes.size === 1).toBe(false);
  });
});

describe('M18a world options', () => {
  test('records without options load with the defaults; invalid fields are dropped', () => {
    expect(normalizeWorldOptions(undefined)).toEqual(DEFAULT_WORLD_OPTIONS);
    expect(normalizeWorldOptions({ startingChest: true })).toEqual({
      structures: true,
      startingChest: true,
    });
    expect(
      normalizeWorldOptions({ structures: false, startingChest: 'yes', biome: 'nowhere' }),
    ).toEqual({ structures: false, startingChest: false });
    expect(normalizeWorldOptions({ biome: 'savanna' }).biome).toBe('savanna');
  });

  test('world types round-trip through the saved world metadata', () => {
    for (const type of ['default', 'flat', 'amplified', 'single_biome'] as const) {
      expect(isWorldType(type)).toBe(true);
      const meta = serializeWorldMetadata({
        seed: 1,
        timeOfDay: 0,
        weather: 'clear',
        manualOverride: false,
        strikeCounter: 0,
        lastTick: 0,
        elapsed: 0,
        breakCount: 0,
        worldType: type,
      });
      expect(deserializeWorldMetadata(meta).worldType).toBe(type);
    }
    expect(isWorldType('hilly')).toBe(false);
  });
});
