import { vec3 } from 'gl-matrix';
import rawSplashes from '../../data/splashes.json';
import type { Camera } from '../render/camera';
import type { GLWrapper } from '../render/gl';
import { MenuOverlayRenderer, overlayLayer, type OverlayLayer } from '../render/menu-overlay';
import { deriveSeed, hashString } from '../engine/rng';
import { sampleTerrainTopY } from '../gen/terrain-height';
import { withTerrainVariant } from '../gen/world-options';
import { PANORAMA_SEED, type WorldManager } from '../world/world-manager';
import { drawButton, drawPanel, UI, uiScaleFor, type Rect } from './ui-kit';
import { drawText, GLYPH_HEIGHT, textWidth } from './pixel-font';
import { renderLogo } from './logo';

/** The splash lines one is picked from each time the menu is shown (data/splashes.json). */
export const SPLASHES: readonly string[] = rawSplashes as string[];

/** The panorama starts streaming this long after the menu appears. */
export const PANORAMA_DELAY_MS = 1000;
/** The panorama fades in from the menu's sky colour over this long. */
export const PANORAMA_FADE_MS = 1500;
/** One full turn of the panorama camera. */
export const PANORAMA_TURN_MS = 120_000;
const SPLASH_COLOR = '#ffe23a';
const SPLASH_SHADOW = '#3d3108';
const LOGO_Y = 26;
const BUTTON_W = 150;
const BUTTON_H = 20;

type MenuButton = 'singleplayer' | 'credits' | 'back';

const BUTTON_LABELS: Record<MenuButton, { text: string; aria: string }> = {
  singleplayer: { text: 'SINGLEPLAYER', aria: 'Singleplayer' },
  credits: { text: 'CREDITS', aria: 'Credits' },
  back: { text: 'BACK', aria: 'Back' },
};

const CREDITS = [
  'BLOCKCRAFT',
  '',
  'AN ORIGINAL VOXEL SANDBOX,',
  'BUILT ONE TASK AT A TIME.',
  '',
  'EVERY TEXTURE, SOUND AND LETTER',
  'IS GENERATED BY CODE.',
  'NO ASSETS FROM OTHER GAMES.',
  '',
  'THANKS FOR PLAYING!',
];

/** Picks a splash line; `random` is injectable for tests. */
export function pickSplash(random: () => number = Math.random): string {
  return SPLASHES[Math.floor(random() * SPLASHES.length) % SPLASHES.length]!;
}

/**
 * The main menu: the live panorama behind a code-drawn logo, a splash line and the menu buttons.
 * Its pixel art is drawn on 2D canvases at UI resolution and composited into the WebGL frame, so
 * the menu is one presented frame. Transparent DOM buttons over the drawn ones take the clicks
 * and keyboard focus and give the buttons their accessible names.
 */
export class MainMenu {
  public visible = false;
  private credits = false;
  private readonly root: HTMLDivElement;
  private readonly buttons = new Map<MenuButton, HTMLButtonElement>();
  private readonly base: OverlayLayer;
  /** One pixel of the cleared sky colour, stretched over the panorama while it fades in. */
  private readonly veil: OverlayLayer;
  private readonly splashCanvas: HTMLCanvasElement;
  private readonly logoCanvas: HTMLCanvasElement;
  private renderer: MenuOverlayRenderer | null = null;
  private splash = '';
  private hovered: MenuButton | null = null;
  // The menu itself is static: its frame is drawn again only when something on it changed.
  private frameDirty = true;
  private panoramaTimer: number | undefined;
  private panoramaStart = 0;
  private panoramaY = 100;
  private scale = 1;
  private uiW = 320;
  private uiH = 240;

  constructor(
    private readonly gl: GLWrapper,
    private readonly camera: Camera,
    private readonly manager: WorldManager,
    private readonly openWorldList: () => void,
  ) {
    const logo = renderLogo();
    this.logoCanvas = document.createElement('canvas');
    this.logoCanvas.width = logo.width;
    this.logoCanvas.height = logo.height;
    this.logoCanvas
      .getContext('2d')!
      .putImageData(new ImageData(logo.data, logo.width, logo.height), 0, 0);
    this.base = overlayLayer(document.createElement('canvas'));
    const veilCanvas = document.createElement('canvas');
    veilCanvas.width = 1;
    veilCanvas.height = 1;
    this.veil = overlayLayer(veilCanvas);

    this.root = document.createElement('div');
    this.root.id = 'main-menu';
    Object.assign(this.root.style, {
      position: 'fixed',
      inset: '0',
      display: 'none',
      zIndex: '5',
    });
    for (const name of Object.keys(BUTTON_LABELS) as MenuButton[]) {
      const button = document.createElement('button');
      button.type = 'button';
      button.textContent = BUTTON_LABELS[name].aria;
      button.setAttribute('aria-label', BUTTON_LABELS[name].aria);
      Object.assign(button.style, {
        position: 'absolute',
        margin: '0',
        padding: '0',
        border: 'none',
        background: 'transparent',
        color: 'transparent',
        outline: 'none',
        cursor: 'pointer',
        font: '1px monospace',
      });
      button.addEventListener('click', () => {
        // Keys typed into the screen this opens must not activate the button again.
        button.blur();
        this.activate(name);
      });
      const hover = (on: boolean) => () => {
        this.hovered = on ? name : this.hovered === name ? null : this.hovered;
        this.invalidate();
      };
      button.addEventListener('mouseenter', hover(true));
      button.addEventListener('mouseleave', hover(false));
      button.addEventListener('focus', hover(true));
      button.addEventListener('blur', hover(false));
      this.buttons.set(name, button);
      this.root.appendChild(button);
    }
    // The splash pulses by CSS animation, so the static menu frame needs no redraws for it.
    const style = document.createElement('style');
    style.textContent =
      '@keyframes blockcraft-splash{0%,100%{transform:translate(-50%,-50%) rotate(-20deg) scale(1)}' +
      '50%{transform:translate(-50%,-50%) rotate(-20deg) scale(1.08)}}';
    document.head.appendChild(style);
    this.splashCanvas = document.createElement('canvas');
    this.splashCanvas.id = 'main-menu-splash';
    Object.assign(this.splashCanvas.style, {
      position: 'absolute',
      imageRendering: 'pixelated',
      pointerEvents: 'none',
      animation: 'blockcraft-splash 900ms ease-in-out infinite',
    });
    this.root.appendChild(this.splashCanvas);
    document.body.appendChild(this.root);
    window.addEventListener('keydown', this.onKeyDown);
  }

  private invalidate(): void {
    this.base.dirty = true;
    this.frameDirty = true;
  }

  /** True when the frame loop has to draw a frame: the menu changed or the panorama is moving. */
  get needsFrame(): boolean {
    return this.visible && (this.frameDirty || this.manager.panorama);
  }

  /** Shows the menu with a fresh splash line; the panorama starts streaming a second later. */
  show(): void {
    this.visible = true;
    this.credits = false;
    this.hovered = null;
    this.splash = pickSplash();
    this.drawSplash();
    this.root.style.display = 'block';
    this.layout();
    window.clearTimeout(this.panoramaTimer);
    this.panoramaTimer = window.setTimeout(() => this.beginPanorama(), PANORAMA_DELAY_MS);
  }

  /** Hides the menu (a world is starting); the world manager tears the panorama down itself. */
  hide(): void {
    if (!this.visible) return;
    this.visible = false;
    window.clearTimeout(this.panoramaTimer);
    this.panoramaTimer = undefined;
    this.root.style.display = 'none';
  }

  /** The current splash line (for tests reading the menu state). */
  get splashText(): string {
    return this.splash;
  }

  private beginPanorama(): void {
    this.panoramaTimer = undefined;
    if (!this.visible || this.manager.world) return;
    // A scenic height: clear of the highest terrain within a few columns of the origin.
    const terrainSeed = deriveSeed(hashString(PANORAMA_SEED), 'terrain_shape');
    let top = 64;
    withTerrainVariant({ type: 'default' }, () => {
      for (let x = -32; x <= 48; x += 8)
        for (let z = -32; z <= 48; z += 8)
          top = Math.max(top, sampleTerrainTopY(terrainSeed, x, z));
    });
    this.panoramaY = top + 14;
    this.panoramaStart = performance.now();
    this.manager.startPanorama();
    this.updateCamera(this.panoramaStart);
  }

  /** Turns the panorama camera: one revolution every 120 s around a fixed point. */
  updateCamera(now: number): void {
    const turn = ((now - this.panoramaStart) / PANORAMA_TURN_MS) * Math.PI * 2;
    this.camera.position = vec3.fromValues(8, this.panoramaY, 8);
    this.camera.yaw = -Math.PI / 2 + turn;
    this.camera.pitch = -0.22;
    this.camera.updateView();
  }

  private activate(name: MenuButton): void {
    if (!this.visible) return;
    if (name === 'singleplayer') this.openWorldList();
    else if (name === 'credits') this.credits = true;
    else this.credits = false;
    this.hovered = null;
    this.layout();
  }

  private readonly onKeyDown = (event: KeyboardEvent): void => {
    if (!this.visible || !this.credits || event.key !== 'Escape') return;
    event.preventDefault();
    this.activate('back');
  };

  private buttonRects(): Partial<Record<MenuButton, Rect>> {
    const x = Math.floor((this.uiW - BUTTON_W) / 2);
    if (this.credits)
      return { back: { x, y: Math.floor(this.uiH / 2) + 74, w: BUTTON_W, h: BUTTON_H } };
    return {
      singleplayer: { x, y: 110, w: BUTTON_W, h: BUTTON_H },
      credits: { x, y: 136, w: BUTTON_W, h: BUTTON_H },
    };
  }

  /** Sizes the overlay to the frame and places the DOM buttons over the drawn ones. */
  private layout(): void {
    const width = this.gl.gl.drawingBufferWidth;
    const height = this.gl.gl.drawingBufferHeight;
    this.scale = uiScaleFor(width, height);
    this.uiW = Math.ceil(width / this.scale);
    this.uiH = Math.ceil(height / this.scale);
    const canvas = this.base.source;
    if (canvas.width !== this.uiW || canvas.height !== this.uiH) {
      canvas.width = this.uiW;
      canvas.height = this.uiH;
    }
    // Canvas pixels → CSS pixels (the game canvas is sized to the window in CSS pixels).
    const css = window.innerWidth / width;
    const rects = this.buttonRects();
    for (const [name, button] of this.buttons) {
      const rect = rects[name];
      button.style.display = rect ? 'block' : 'none';
      if (!rect) continue;
      Object.assign(button.style, {
        left: `${rect.x * this.scale * css}px`,
        top: `${rect.y * this.scale * css}px`,
        width: `${rect.w * this.scale * css}px`,
        height: `${rect.h * this.scale * css}px`,
      });
    }
    // The splash sits on the logo's lower right, centred on this point.
    const logo = this.logoRect();
    const splash = this.splashCanvas.style;
    splash.display = this.credits ? 'none' : 'block';
    splash.left = `${(logo.x + logo.w - 16) * this.scale * css}px`;
    splash.top = `${(logo.y + logo.h + 18) * this.scale * css}px`;
    splash.width = `${this.splashCanvas.width * this.scale * css}px`;
    splash.height = `${this.splashCanvas.height * this.scale * css}px`;
    this.invalidate();
  }

  private drawSplash(): void {
    const canvas = this.splashCanvas;
    canvas.width = textWidth(this.splash) + 1;
    canvas.height = GLYPH_HEIGHT + 1;
    canvas.setAttribute('aria-label', this.splash);
    const ctx = canvas.getContext('2d')!;
    ctx.clearRect(0, 0, canvas.width, canvas.height);
    drawText(ctx, this.splash, 0, 0, 1, SPLASH_COLOR, SPLASH_SHADOW);
  }

  private logoRect(): Rect {
    return {
      x: Math.floor((this.uiW - this.logoCanvas.width) / 2),
      y: LOGO_Y,
      w: this.logoCanvas.width,
      h: this.logoCanvas.height,
    };
  }

  private drawBase(): void {
    const ctx = this.base.source.getContext('2d')!;
    ctx.imageSmoothingEnabled = false;
    ctx.clearRect(0, 0, this.uiW, this.uiH);
    const logo = this.logoRect();
    ctx.drawImage(this.logoCanvas, logo.x, logo.y);
    if (this.credits) {
      ctx.fillStyle = 'rgba(9, 11, 20, 0.55)';
      ctx.fillRect(0, 0, this.uiW, this.uiH);
      ctx.drawImage(this.logoCanvas, logo.x, logo.y);
      const panel = { x: Math.floor((this.uiW - 220) / 2), y: 72, w: 220, h: 112 };
      drawPanel(ctx, panel, 1);
      CREDITS.forEach((line, index) => {
        if (!line) return;
        drawText(
          ctx,
          line,
          panel.x + Math.floor((panel.w - textWidth(line)) / 2),
          panel.y + 8 + index * 10,
          1,
          index === 0 ? UI.accent : UI.text,
          UI.outline,
        );
      });
    }
    const rects = this.buttonRects();
    for (const name of Object.keys(rects) as MenuButton[])
      drawButton(ctx, rects[name]!, BUTTON_LABELS[name].text, 1, this.hovered === name);
    if (!this.credits) {
      const left = 'BLOCKCRAFT M18';
      const right = 'NOTHING HERE WAS DOWNLOADED';
      drawText(ctx, left, 3, this.uiH - 10, 1, UI.text, UI.outline);
      drawText(ctx, right, this.uiW - textWidth(right) - 4, this.uiH - 10, 1, UI.text, UI.outline);
    }
  }

  /** Draws the menu over the frame the world manager just rendered (or over the cleared sky). */
  render(): void {
    if (!this.visible) return;
    this.frameDirty = false;
    const gl = this.gl.gl;
    if (
      Math.ceil(gl.drawingBufferWidth / this.scale) !== this.uiW ||
      Math.ceil(gl.drawingBufferHeight / this.scale) !== this.uiH ||
      uiScaleFor(gl.drawingBufferWidth, gl.drawingBufferHeight) !== this.scale
    )
      this.layout();
    this.renderer ??= new MenuOverlayRenderer(this.gl);
    if (this.base.dirty) this.drawBase();
    const s = this.scale;
    if (this.manager.panorama) {
      const veil = 1 - (performance.now() - this.panoramaStart) / PANORAMA_FADE_MS;
      if (veil > 0) {
        const [r, g, b] = gl.getParameter(gl.COLOR_CLEAR_VALUE) as Float32Array;
        const ctx = this.veil.source.getContext('2d')!;
        ctx.fillStyle = `rgb(${Math.round(r! * 255)}, ${Math.round(g! * 255)}, ${Math.round(b! * 255)})`;
        ctx.fillRect(0, 0, 1, 1);
        this.veil.dirty = true;
        this.renderer.draw(this.veil, 0, 0, this.uiW * s, this.uiH * s, 0, veil);
      }
    }
    this.renderer.draw(this.base, 0, 0, this.uiW * s, this.uiH * s);
  }
}

/** Holder for the running menu, so the debug API and tests can reach it. */
export const activeMenu: { menu: MainMenu | null } = { menu: null };
